import type { Metadata } from "next";
import { Geist_Mono, Space_Grotesk, Syne } from "next/font/google";
import { ThemeProvider } from "next-themes";
import "./globals.css";
import { Toaster } from "@/components/ui/sonner";

// Website-wide UI font: geometric, technical, but readable. Drives --font-sans,
// which the `font-sans` utility (and the base `html`) use everywhere.
const spaceGrotesk = Space_Grotesk({
    variable: "--font-sans",
    subsets: ["latin"],
});

const geistMono = Geist_Mono({
    variable: "--font-geist-mono",
    subsets: ["latin"],
});

// Display font for the sidebar brand title.
const syne = Syne({
    variable: "--font-syne",
    subsets: ["latin"],
});

export const metadata: Metadata = {
    title: "Create Next App",
    description: "Generated by create next app",
};

// Root layout: only the document shell + fonts + global toaster. The app shell
// (sidebar/header) lives in the (main) route group so (standalone) pages like
// login render bare.
export default function RootLayout({
    children,
}: Readonly<{
    children: React.ReactNode;
}>) {
    return (
        // suppressHydrationWarning: next-themes sets the theme class on <html>
        // before paint, which would otherwise mismatch the server markup.
        <html
            lang="en"
            suppressHydrationWarning
            className={`${spaceGrotesk.variable} ${geistMono.variable} ${syne.variable} h-full antialiased`}
        >
            <body className="h-full">
                <ThemeProvider
                    attribute="class"
                    defaultTheme="system"
                    enableSystem
                    disableTransitionOnChange
                >
                    {children}
                    <Toaster />
                </ThemeProvider>
            </body>
        </html>
    );
}
